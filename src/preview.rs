/// `preview_to_image` of the `factors` map: RGB8 rows. `at(c, y, x)` reads one latent value.
fn rgb(factors: &[[f32; 3]], bias: [f32; 3], h: usize, w: usize, at: impl Fn(usize, usize, usize) -> f32) -> Vec<u8> {
    let mut out = Vec::with_capacity(h * w * 3);
    for y in 0..h {
        for x in 0..w {
            for i in 0..3 {
                let v: f32 = factors.iter().enumerate().map(|(c, f)| f[i] * at(c, y, x)).sum::<f32>() + bias[i];
                out.push((((v + 1.0) / 2.0).clamp(0.0, 1.0) * 255.0) as u8);
            }
        }
    }
    out
}

/// Krea 2 and Anima: a [16, h, w] latent to [h, w, 3].
pub fn wan21(x0: &[f32], h: usize, w: usize) -> Vec<u8> {
    rgb(&WAN21.0, WAN21.1, h, w, |c, y, x| x0[(c * h + y) * w + x])
}

/// MOSS Image: a [128, h, w] latent to [2h, 2w, 3], each channel group being 32 of 2 x 2 pixels.
pub fn flux2(x0: &[f32], h: usize, w: usize) -> Vec<u8> {
    rgb(&FLUX2.0, FLUX2.1, h * 2, w * 2, |c, y, x| x0[((c * 4 + y % 2 * 2 + x % 2) * h + y / 2) * w + x / 2])
}

/// MiniMax H3: the first frame of a [24, t, h, w] latent to [h, w, 3].
pub fn h3(x0: &[f32], t: usize, h: usize, w: usize) -> Vec<u8> {
    rgb(&H3_VIDEO.0, H3_VIDEO.1, h, w, |c, y, x| x0[(c * t * h + y) * w + x])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_zero_latent_shows_the_bias() {
        let px = wan21(&[0.0; 16], 1, 1);
        assert_eq!(px, [((1.0f32 - 0.1835) / 2.0 * 255.0) as u8, ((1.0f32 - 0.0868) / 2.0 * 255.0) as u8, ((1.0f32 - 0.3360) / 2.0 * 255.0) as u8]);
    }

    #[test]
    fn flux2_packs_channel_groups_into_pixels() {
        // torch: t.reshape(1, 32, 2, 2, 1, 1).permute(0, 1, 4, 2, 5, 3).reshape(1, 32, 2, 2)
        let mut x0 = vec![0.0; 128];
        x0[3 * 4 + 1] = 1.0; // group 3, second of the group: the top right pixel
        let px = flux2(&x0, 1, 1);
        let bias = flux2(&[0.0; 128], 1, 1);
        assert_eq!(px.len(), 12);
        assert_ne!(px[3..6], bias[3..6]);
        assert_eq!(px[..3], bias[..3]);
        assert_eq!(px[6..], bias[6..]);
    }
}
