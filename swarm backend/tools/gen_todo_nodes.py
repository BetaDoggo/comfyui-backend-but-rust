"""Generates crates/comfy-server/src/todo_nodes.json: the compatibility backlog the server loads at startup.

Usage (from the repo root):
    python tools/gen_todo_nodes.py <real ComfyUI object_info.json> <inventory.json> [param_probe.json] [--prune]

- real object_info: GET /object_info from a stock ComfyUI with SwarmUI's ExtraNodes loaded
  (see docs/COMPATIBILITY.md, "Regenerating"). Supplies the exact schema for each node.
- inventory.json: output of tools/swarm_inventory.py (where SwarmUI's generator emits each node).
- param_probe.json: output of tools/probe_swarm_params.py (which SwarmUI params produced each node live).
"""
import json, sys, pathlib

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from todo_catalog import AREAS, NODES

real = json.load(open(sys.argv[1], encoding='utf-8'))
# Hand-written schemas for third-party node packs (tools/third_party_schemas.py).
third_party = json.load(open(pathlib.Path(__file__).parent / 'data' / 'third_party_schemas.json', encoding='utf-8'))
inv = json.load(open(sys.argv[2], encoding='utf-8'))
probe = json.load(open(sys.argv[3], encoding='utf-8')) if len(sys.argv) > 3 and not sys.argv[3].startswith('--') else {'cases': []}

unclassified = [n for n in inv['not_implemented'] if n not in NODES]
if unclassified:
    sys.exit(f'classify these in tools/todo_catalog.py first: {unclassified}')

# Implemented nodes drop out of the backlog. With --prune, also delete their catalog lines.
implemented = [n for n in NODES if n in inv['emitted_nodes'] and n not in inv['not_implemented']]
if implemented and '--prune' in sys.argv:
    cat = pathlib.Path(__file__).parent / 'todo_catalog.py'
    lines = cat.read_text(encoding='utf-8').splitlines(keepends=True)
    cat.write_text(''.join(l for l in lines if not any(l.strip().startswith(f"'{n}':") for n in implemented)), encoding='utf-8')
    print(f'pruned {len(implemented)} implemented node(s) from todo_catalog.py: {implemented}')
NODES = {k: v for k, v in NODES.items() if k not in implemented}

where = {}
for b in inv['blocks']:
    for n in b['nodes']:
        where.setdefault(n, []).append(f"{b['file'].split('/')[-1]}:{b['line']}")

triggers = {}
for case in probe['cases']:
    for n in case.get('new_nodes', []):
        triggers.setdefault(n, [])
        if case['param'] not in triggers[n]:
            triggers[n].append(case['param'])

nodes = {}
for cls, (area, needs, note) in sorted(NODES.items()):
    nodes[cls] = {
        'area': area,
        'needs': needs,
        'note': note,
        'triggers': triggers.get(cls, []),
        'swarm_source': sorted(set(where.get(cls, []))),
        'object_info': real.get(cls) or third_party.get(cls),
    }

out = {
    'about': 'Generated by tools/gen_todo_nodes.py. ComfyUI node classes SwarmUI can emit that comfy-server does not implement yet.',
    'areas': {k: {'title': t, 'swarm_params': p} for k, (t, p) in AREAS.items()},
    'nodes': nodes,
}
path = pathlib.Path('crates/comfy-server/src/todo_nodes.json')
path.write_text(json.dumps(out, indent=1, ensure_ascii=False) + '\n', encoding='utf-8')
print(f'{len(nodes)} todo nodes ({sum(1 for n in nodes.values() if n["object_info"])} with real schemas) -> {path} ({path.stat().st_size // 1024} KiB)')
